def _catalog(values: dict[str, str]) -> dict[tuple[str, str], str]:
    # Blender uses a dedicated context for operator labels/buttons. Register
    # both contexts so a translated panel never leaves its actions in English.
    return {
        (context, source): target
        for source, target in values.items()
        for context in ("*", "Operator")
    }


